export const ROI_CALCULATOR = {
  assumptions: {
    avgLeadsLostPerMonth: 15,
    avgCustomerValue: 500,
    recoveryRate: 0.4,
  },
  calculate: (leadsPerMonth: number = 15, customerValue: number = 500) => {
    const leadsRecovered = Math.floor(leadsPerMonth * 0.4);
    const monthlyRevenue = leadsRecovered * customerValue;
    const annualRevenue = monthlyRevenue * 12;
    const coreCost = 154;
    const annualCost = coreCost * 12;
    const netAnnualGain = annualRevenue - annualCost;
    const roi = ((netAnnualGain / annualCost) * 100).toFixed(0);

    return {
      leadsRecovered,
      monthlyRevenue,
      annualRevenue,
      annualCost,
      netAnnualGain,
      roi: `${roi}%`,
      paybackPeriod: monthlyRevenue > coreCost ? "First month" : "2-3 months",
    };
  },
};

